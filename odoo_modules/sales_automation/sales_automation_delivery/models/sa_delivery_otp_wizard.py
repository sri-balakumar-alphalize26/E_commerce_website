"""The counter's side of the OTPs, as buttons in Odoo (owner, 30 Sep 2026):

  Delivery ▸ Create OTP     pick the order, get the pickup / delivery code on
                            screen (copyable) - it is also sent on WhatsApp
  job ▸ Pickup              type the pickup code   -> picked + dispatched
  job ▸ Delivered           type the customer code -> delivered, order closed
  job ▸ Failed              reason -> failed, customer and shop told

The app (later) calls the same picking methods, so behaviour cannot drift.
"""
from odoo import _, api, fields, models
from odoo.exceptions import UserError

_JOB_STATES = ('awaiting_shop', 'preparing', 'ready', 'to_assign', 'offered',
               'accepted', 'picked', 'dispatched', 'out_for_delivery')


class SaDeliveryOtpWizard(models.TransientModel):
    _name = 'sa.delivery.otp.wizard'
    _description = 'Create a delivery OTP'

    picking_id = fields.Many2one(
        'stock.picking', 'Order / job', required=True,
        domain="[('picking_type_code', '=', 'outgoing'), ('sa_delivery_state', 'in', %s)]" % (list(_JOB_STATES),),
        help="Search by the sale order (S00013), the customer or the job "
             "reference (D42).")
    kind = fields.Selection([
        ('pickup', 'Pickup / Dispatch - the rider collects from the shop'),
        ('delivery', 'Delivery - the customer confirms receipt'),
    ], required=True, default='pickup')
    send_to = fields.Selection([
        ('auto', 'Send on WhatsApp (pickup → rider, delivery → customer)'),
        ('none', 'Do not send - I will pass the code on myself'),
    ], 'Send', required=True, default='auto')
    # result
    state = fields.Selection([('new', 'New'), ('done', 'Done')], default='new')
    code = fields.Char('Code', readonly=True)
    ref = fields.Char('Job', readonly=True)
    sent_to = fields.Char('Sent to', readonly=True)
    expires_on = fields.Datetime('Valid until', readonly=True)
    message = fields.Char('Result', readonly=True)

    def action_generate(self):
        self.ensure_one()
        picking = self.picking_id.sudo()
        if self.kind == 'pickup':
            ok, msg, code = picking.sa_issue_pickup_otp(
                to='rider' if self.send_to == 'auto' else 'none')
        else:
            ok, msg, code = picking.sa_issue_delivery_otp(
                send=(self.send_to == 'auto'))
        if not code:
            raise UserError(msg or _("No code could be made."))
        otp = self.env['sa.delivery.otp'].sudo().search(
            [('picking_id', '=', picking.id), ('kind', '=', self.kind),
             ('active', '=', True)], order='id desc', limit=1)
        picking.message_post(body=_(
            "%(kind)s code generated by %(user)s%(sent)s.",
            kind=dict(self._fields['kind'].selection)[self.kind].split(' - ')[0],
            user=self.env.user.name,
            sent=(_(", sent to %s", otp.sent_to) if ok and otp.sent_to else
                  _(", not sent (%s)", msg) if not ok else '')))
        self.write({'state': 'done', 'code': code, 'ref': picking.sa_ref_code or picking.name,
                    'sent_to': otp.sent_to or '', 'expires_on': otp.expires_on,
                    'message': msg or ''})
        return {'type': 'ir.actions.act_window', 'res_model': self._name,
                'res_id': self.id, 'view_mode': 'form', 'target': 'new',
                'name': _('Delivery code')}


class SaDeliveryOtpEntry(models.TransientModel):
    """The dialog behind the Pickup / Delivered buttons: type the code."""
    _name = 'sa.delivery.otp.entry'
    _description = 'Enter a delivery OTP'

    picking_id = fields.Many2one('stock.picking', required=True)
    kind = fields.Selection([('pickup', 'Pickup'), ('delivery', 'Delivery')], required=True)
    code = fields.Char('Code', required=True, size=6)
    hint = fields.Char(compute='_compute_hint')
    rider_id = fields.Many2one('sa.delivery.partner', 'Rider collecting',
                               help="Who is taking the parcel. Pre-filled when the job "
                                    "already has a rider; otherwise pick one.")
    has_rider = fields.Boolean(compute='_compute_has_rider')

    @api.depends('picking_id')
    def _compute_has_rider(self):
        for w in self:
            w.has_rider = bool(w.picking_id.sa_delivery_partner_id)

    @api.depends('kind', 'picking_id')
    def _compute_hint(self):
        for w in self:
            if w.kind == 'pickup':
                w.hint = _("Dispatch: choose the rider and type the 6-digit pickup "
                           "code (Generate Pickup Code on the job, or Delivery ▸ Create "
                           "OTP). The parcel then leaves with the rider.")
            else:
                w.hint = _("Delivered: type the 6-digit code the customer received on "
                           "WhatsApp when the rider reached them. Ask the customer for "
                           "it after handing over the parcel.")

    def action_verify(self):
        self.ensure_one()
        picking = self.picking_id.sudo()
        if self.kind == 'pickup':
            picking.sa_action_dispatch_with_otp(self.code, rider_id=self.rider_id.id)
        else:
            picking.sa_action_deliver_with_otp(self.code)
        return {'type': 'ir.actions.client', 'tag': 'reload'}


class SaDeliveryFailWizard(models.TransientModel):
    _name = 'sa.delivery.fail.wizard'
    _description = 'Mark a delivery as failed'

    picking_id = fields.Many2one('stock.picking', required=True)
    reason = fields.Selection([
        ('absent', 'Customer not available'),
        ('refused', 'Customer refused the parcel'),
        ('address', 'Wrong / unreachable address'),
        ('damaged', 'Parcel damaged'),
        ('other', 'Other'),
    ], required=True, default='absent')
    note = fields.Char('Note')

    def action_fail(self):
        self.ensure_one()
        label = dict(self._fields['reason'].selection)[self.reason]
        reason = ('%s - %s' % (label, self.note)) if self.note else label
        self.picking_id.sudo().sa_action_fail(reason)
        return {'type': 'ir.actions.client', 'tag': 'reload'}
